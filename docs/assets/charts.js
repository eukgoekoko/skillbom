/* Interactive charts for the corpus study.
   Each <figure data-chart="…" data-src="…json"> holds a static fallback generated by
   scripts/corpus/publish.py; this script replaces it with a chart drawn from the same
   published summary JSON, adds view toggles and a clickable legend, and animates bars
   into place. Tooltips come from the layout's data-tip handler. */
(() => {
  const figures = [...document.querySelectorAll('figure[data-chart]')];
  if (!figures.length || !window.fetch) return;
  const reduceMotion = matchMedia('(prefers-reduced-motion: reduce)').matches;
  const pct = v => v.toFixed(1) + '%';
  const num = v => v.toLocaleString('en-US');

  function el(tag, attrs = {}, ...children) {
    const e = document.createElement(tag);
    for (const [k, v] of Object.entries(attrs)) {
      if (k === 'class') e.className = v;
      else if (k === 'text') e.textContent = v;
      else e.setAttribute(k, v);
    }
    children.forEach(c => c && e.append(c));
    return e;
  }

  const SOURCES = [['parentManifest', 'Parent plugin manifest'], ['repoLicenseFile', 'Repository LICENSE file'],
                   ['own', 'The skill itself'], ['none', 'No license anywhere']];
  const KINDS = [['anyUnlicensedPct', 'No license at all'], ['anyCopyleftPct', 'Copyleft'],
                 ['anyProprietaryPct', 'Proprietary'], ['anyNonCommercialPct', 'Non-commercial'],
                 ['anySourceAvailablePct', 'Source-available'], ['anyCustomPct', 'Custom terms']];
  const MEASURES = [['allSkillsOwnLicensePct', 'License every skill individually'],
                    ['anyUnlicensedPct', 'Contain a skill with no license']];

  // Each spec returns { views: {key: {label, sub, rows:[{label, value, tip}]}}, scale } or a grouped spec.
  const SPECS = {
    'license-source': d => {
      const view = (src, who) => ({
        sub: `Share of ${num(src.skills)} ${who}, by the evidence their license was resolved from`,
        rows: SOURCES.map(([k, label]) => ({
          label, value: src[k].pct,
          tip: `${label}: ${num(src[k].count)} of ${num(src.skills)} skills (${pct(src[k].pct)})`,
        })),
      });
      return { scale: 100, views: {
        all: { label: 'All public skills', ...view(d.licenseSource, 'public skills') },
        om: { label: 'Official marketplace', ...view(d.licenseSourceOfficialMarketplace, 'skills in the official marketplace') },
      } };
    },
    restrictive: d => {
      const view = (r, who) => ({
        sub: `Share of the ${num(r.repos)} ${who}`,
        rows: KINDS.map(([k, label]) => ({ label, value: r[k], tip: `${label}: ${pct(r[k])} of ${num(r.repos)} repositories` })),
      });
      const scale = Math.max(...KINDS.flatMap(([k]) => [d.byRepo[k], d.byRepoOfficialMarketplace[k]]));
      return { scale, views: {
        all: { label: 'All repositories', ...view(d.byRepo, 'repositories that contain skills') },
        om: { label: 'Official marketplace', ...view(d.byRepoOfficialMarketplace, 'official-marketplace repositories with skills') },
      } };
    },
    'repo-size': d => {
      const s = d.drilldown.skillsPerRepo, repos = d.drilldown.repos;
      const total = s.bins.reduce((a, b) => a + b.skills, 0);
      const tip = b => `${b.bin} skills: ${num(b.repos)} repositories, holding ${num(b.skills)} skills`;
      return { scale: 60, views: {
        repos: { label: 'Share of repositories', sub: `Share of the ${num(repos)} repositories that contain skills, by how many they contain`,
                 rows: s.bins.map(b => ({ label: b.bin, value: 100 * b.repos / repos, tip: tip(b) })) },
        skills: { label: 'Share of skills', sub: `Share of all ${num(total)} skills, by the size of the repository they sit in`,
                  rows: s.bins.map(b => ({ label: b.bin, value: 100 * b.skills / total, tip: tip(b) })) },
      } };
    },
    marketplace: d => ({
      grouped: true, scale: 25,
      series: [['s1', 'All repositories', d.byRepo], ['s2', 'Official Claude Code marketplace', d.byRepoOfficialMarketplace]],
      groups: MEASURES.map(([k, label]) => ({
        label,
        rows: [['s1', 'All repositories', d.byRepo], ['s2', 'Official marketplace', d.byRepoOfficialMarketplace]].map(
          ([s, name, r]) => ({ series: s, label: name, value: r[k], tip: `${label}: ${name} (${num(r.repos)} repositories), ${pct(r[k])}` })),
      })),
    }),
  };

  function rowEl(row) {
    const bar = el('span', { class: `chart-bar ${row.series || 's1'}` });
    const value = el('span', { class: 'chart-value' });
    const r = el('div', { class: 'chart-row', tabindex: '0' },
      el('span', { class: 'chart-label', text: row.label }), el('span', { class: 'chart-track' }, bar), value);
    r._bar = bar; r._value = value;
    return r;
  }

  function setRow(r, row, scale, visible) {
    r.dataset.tip = row.tip;
    r._value.textContent = pct(row.value);
    r._bar.style.width = visible ? `${Math.max(100 * row.value / scale, 0.6)}%` : '0%';
  }

  // Grow the bars from zero right after rendering. A scroll-triggered reveal left them empty
  // whenever the observer didn't fire; the timeout covers browsers that throttle frames.
  function reveal(draw) {
    if (reduceMotion) return draw();
    requestAnimationFrame(() => requestAnimationFrame(draw));
    setTimeout(draw, 300);
  }

  function renderViews(fig, spec) {
    const sub = fig.querySelector('figcaption span');
    const keys = Object.keys(spec.views);
    const controls = el('div', { class: 'chart-controls', role: 'group', 'aria-label': 'Show data for' });
    const bars = el('div', { class: 'chart-bars', role: 'img' });
    const rows = spec.views[keys[0]].rows.map(rowEl);
    rows.forEach(r => bars.append(r));
    let shown = false, current = keys[0];
    const draw = () => {
      const v = spec.views[current];
      sub.textContent = v.sub;
      bars.setAttribute('aria-label', `${fig.querySelector('figcaption b').textContent}, ${v.label}: ` +
        v.rows.map(x => `${x.label} ${pct(x.value)}`).join(', '));
      v.rows.forEach((row, i) => setRow(rows[i], row, spec.scale, shown));
      controls.querySelectorAll('button').forEach(b => b.setAttribute('aria-pressed', String(b.dataset.view === current)));
    };
    keys.forEach(k => {
      const b = el('button', { type: 'button', 'data-view': k, text: spec.views[k].label });
      b.addEventListener('click', () => { current = k; draw(); });
      controls.append(b);
    });
    fig.querySelector('.chart-bars').replaceWith(controls, bars);
    draw();
    reveal(() => { shown = true; draw(); });
  }

  function renderGrouped(fig, spec) {
    const legend = el('div', { class: 'chart-legend', role: 'group', 'aria-label': 'Series' });
    const bars = el('div', { class: 'chart-bars' });
    const off = new Set();
    const rows = [];
    spec.groups.forEach(g => {
      const group = el('div', { class: 'chart-group', role: 'img', 'aria-label': `${g.label}: ` +
        g.rows.map(r => `${r.label} ${pct(r.value)}`).join(', ') }, el('span', { class: 'chart-group-label', text: g.label }));
      g.rows.forEach(row => { const r = rowEl(row); rows.push([r, row]); group.append(r); });
      bars.append(group);
    });
    let shown = false;
    const draw = () => rows.forEach(([r, row]) => {
      const visible = shown && !off.has(row.series);
      r.classList.toggle('off', off.has(row.series));
      setRow(r, row, spec.scale, visible);
    });
    spec.series.forEach(([s, label]) => {
      const b = el('button', { type: 'button', 'aria-pressed': 'true' }, el('i', { class: s }), label);
      b.addEventListener('click', () => {
        off.has(s) ? off.delete(s) : off.add(s);
        b.setAttribute('aria-pressed', String(!off.has(s)));
        draw();
      });
      legend.append(b);
    });
    fig.querySelector('.chart-legend')?.remove();
    fig.querySelector('.chart-bars').replaceWith(legend, bars);
    draw();
    reveal(() => { shown = true; draw(); });
  }

  fetch(figures[0].dataset.src)
    .then(r => (r.ok ? r.json() : Promise.reject(r.status)))
    .then(data => figures.forEach(fig => {
      const make = SPECS[fig.dataset.chart];
      if (!make) return;
      const spec = make(data);
      (spec.grouped ? renderGrouped : renderViews)(fig, spec);
      fig.classList.add('is-live');
    }))
    .catch(() => { /* keep the static charts */ });
})();

